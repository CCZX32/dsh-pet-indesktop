_CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

#: 12 小时制中文小时（索引 = 小时 % 12；0 点与 12 点都是「十二」）。
_HOUR_CN = (
    "十二",
    "一",
    "二",
    "三",
    "四",
    "五",
    "六",
    "七",
    "八",
    "九",
    "十",
    "十一",
)


def normalize_quotes(value) -> list[str]:
    """把自定义台词清洗成一行一条：去空行、去控制字符、去重、单条截断。

    接受多行字符串（``\\n`` / ``\\r\\n`` / ``\\r``）或已是序列的配置值；
    返回空列表表示「未自定义」，调用方回退内置库。
    """
    if value is None:
        return []
    if isinstance(value, (tuple, list, set)):
        raw_lines = [str(item) for item in value]
    else:
        raw_lines = re.split(r"\r\n|\r|\n", str(value))
    quotes: list[str] = []
    for line in raw_lines:
        text = _CONTROL_RE.sub("", line).strip()
        if not text:
            continue
        text = text[:MAX_QUOTE_LEN].strip()
        if text and text not in quotes:
            quotes.append(text)
    return quotes


def pool(custom=None) -> tuple[str, ...]:
    """当天的台词库：自定义非空时整体替换内置库。"""
    cleaned = normalize_quotes(custom)
    return tuple(cleaned) if cleaned else CHINESE_QUOTES


def period_cn(hour: int) -> str:
    """时段前缀；入参是 24 小时制的小时（0-23）。"""
    if hour < 5:
        return "凌晨"
    if hour < 9:
        return "早上"
    if hour < 12:
        return "上午"
    if hour == 12:
        return "中午"
    if hour < 18:
        return "下午"
    return "晚上"


def spoken_time(now) -> str:
    """口播报时（中文数字）：整点说「九点整」，其余说「九点零五分」。"""
    hour_12 = now.hour % 12 or 12
    hour_cn = _HOUR_CN[hour_12 % 12]
    period = period_cn(now.hour)
    if now.minute == 0:
        return f"现在是{period}{hour_cn}点整"
    return f"现在{period}{hour_cn}点{now.minute:02d}分"


def bubble_time(now) -> str:
    """气泡报时（阿拉伯数字 + 中文时段词），避免中文与数字混排。"""
    return f"现在{period_cn(now.hour)} {now.hour:02d}:{now.minute:02d}"


def spoken_text(now, quote: str = "") -> str:
    base = spoken_time(now)
    return f"{base}。{quote}" if quote else base


def bubble_text(now, quote: str = "") -> str:
    base = bubble_time(now)
    return f"{base}。{quote}" if quote else base
